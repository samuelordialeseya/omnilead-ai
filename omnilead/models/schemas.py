"""
Domain Schemas
==============
All Pydantic v2 models for OmniLead-AI data contracts.
"""
from __future__ import annotations

from enum import Enum
from typing import Optional

from pydantic import BaseModel, EmailStr, Field, HttpUrl


# ─────────────────────────────────────────────────────────────────────────────
# Enums
# ─────────────────────────────────────────────────────────────────────────────

class EmailRisk(str, Enum):
    SAFE = "SAFE"
    CATCH_ALL = "CATCH_ALL"
    DISPOSABLE = "DISPOSABLE"
    NO_MX = "NO_MX"
    INVALID = "INVALID"


class LeadStatus(str, Enum):
    PENDING = "PENDING"
    SCRAPED = "SCRAPED"
    VERIFIED = "VERIFIED"
    ENRICHED = "ENRICHED"
    DISPATCHED = "DISPATCHED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"


# ─────────────────────────────────────────────────────────────────────────────
# Input
# ─────────────────────────────────────────────────────────────────────────────

class RawLead(BaseModel):
    """Minimal input record from CSV / JSON / API."""
    company_name: str = Field(..., description="Name of the target company.", examples=["Acme Corp"])
    website: str = Field(..., description="Company website URL.", examples=["https://acmecorp.com"])
    prospect_name: str = Field(default="", description="Contact person's full name.")
    prospect_email: str = Field(default="", description="Contact person's email address.")
    prospect_role: str = Field(default="", description="Job title / role.", examples=["Head of Growth"])
    niche: str = Field(default="", description="Industry or niche tag.", examples=["B2B SaaS", "E-commerce"])


# ─────────────────────────────────────────────────────────────────────────────
# Intermediate
# ─────────────────────────────────────────────────────────────────────────────

class ScrapedData(BaseModel):
    """Extracted intelligence from the company's website."""
    website: str
    meta_title: str = ""
    meta_description: str = ""
    page_summary: str = Field(default="", description="Cleaned text excerpt from homepage body.")
    detected_stack: list[str] = Field(default_factory=list, description="Tech keywords detected (Shopify, React, HubSpot, etc.)")
    social_links: dict[str, str] = Field(default_factory=dict, description="Discovered social profiles keyed by platform.")
    emails_found: list[str] = Field(default_factory=list, description="Raw email addresses scraped from site.")
    crawl_success: bool = True
    error: Optional[str] = None


class EmailValidationResult(BaseModel):
    """Deliverability report for a prospect email."""
    email: str
    is_valid_format: bool
    domain: str = ""
    mx_records_found: bool = False
    is_disposable: bool = False
    risk: EmailRisk = EmailRisk.INVALID
    deliverability_score: int = Field(default=0, ge=0, le=100)


# ─────────────────────────────────────────────────────────────────────────────
# AI Output (strict JSON schema from Gemini)
# ─────────────────────────────────────────────────────────────────────────────

class AIEnrichment(BaseModel):
    """Structured intelligence generated by Gemini 3.8 Flash."""
    company_summary: str = Field(
        ...,
        description="2-sentence executive summary of what the company does and who they serve.",
    )
    inferred_pain_points: list[str] = Field(
        ...,
        min_length=1,
        max_length=5,
        description="Top operational or growth bottlenecks likely felt by this company.",
    )
    personalized_icebreaker: str = Field(
        ...,
        description="A single hyper-specific cold outreach opening sentence referencing something unique about their business.",
    )
    value_proposition: str = Field(
        ...,
        description="A concise pitch sentence connecting the prospect's pain to automation solutions.",
    )
    icp_score: int = Field(
        ...,
        ge=0,
        le=100,
        description="Ideal Customer Profile match score 0–100. 80+ = hot lead.",
    )
    suggested_cta: str = Field(
        ...,
        description="A suggested call-to-action for the initial outreach email.",
    )


# ─────────────────────────────────────────────────────────────────────────────
# Output
# ─────────────────────────────────────────────────────────────────────────────

class EnrichedLead(BaseModel):
    """Complete unified record ready for export and CRM ingestion."""
    # Raw input fields
    company_name: str
    website: str
    prospect_name: str = ""
    prospect_email: str = ""
    prospect_role: str = ""
    niche: str = ""

    # Scraped intelligence
    meta_title: str = ""
    meta_description: str = ""
    page_summary: str = ""
    detected_stack: list[str] = Field(default_factory=list)
    social_linkedin: str = ""
    social_twitter: str = ""

    # Email verification
    email_valid: bool = False
    email_risk: EmailRisk = EmailRisk.INVALID
    email_deliverability_score: int = 0

    # AI enrichment
    company_summary: str = ""
    pain_points: list[str] = Field(default_factory=list)
    icebreaker: str = ""
    value_proposition: str = ""
    icp_score: int = 0
    suggested_cta: str = ""

    # Metadata
    status: LeadStatus = LeadStatus.PENDING
    dispatch_success: bool = False
    error_message: str = ""

    @property
    def is_hot_lead(self) -> bool:
        return self.icp_score >= 80 and self.email_valid

    def to_csv_row(self) -> dict:
        return {
            "company_name": self.company_name,
            "website": self.website,
            "prospect_name": self.prospect_name,
            "prospect_email": self.prospect_email,
            "prospect_role": self.prospect_role,
            "niche": self.niche,
            "meta_title": self.meta_title,
            "detected_stack": ", ".join(self.detected_stack),
            "social_linkedin": self.social_linkedin,
            "social_twitter": self.social_twitter,
            "email_valid": self.email_valid,
            "email_risk": self.email_risk.value,
            "email_deliverability_score": self.email_deliverability_score,
            "icp_score": self.icp_score,
            "is_hot_lead": self.is_hot_lead,
            "icebreaker": self.icebreaker,
            "value_proposition": self.value_proposition,
            "suggested_cta": self.suggested_cta,
            "company_summary": self.company_summary,
            "pain_points": " | ".join(self.pain_points),
            "status": self.status.value,
        }
